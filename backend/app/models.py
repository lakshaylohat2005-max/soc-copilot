import datetime
from typing import Any, Dict, List, Optional
from sqlalchemy import Column, Integer, String, Text, DateTime, ForeignKey, JSON
from sqlalchemy.orm import relationship
from .db import Base


def utc_now() -> datetime.datetime:
    return datetime.datetime.now(datetime.timezone.utc)


class LogEvent(Base):
    """Normalized ingested security log event."""
    __tablename__ = "log_events"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    source = Column(String(50), nullable=False, index=True)  # ssh, web, firewall
    raw = Column(Text, nullable=False)
    src_ip = Column(String(45), nullable=True, index=True)
    user = Column(String(100), nullable=True, index=True)
    event_type = Column(String(50), nullable=False, index=True)
    status = Column(String(50), default="unknown", nullable=False)
    extra = Column(JSON, nullable=True, default=dict)


class Alert(Base):
    """Detection alert generated by rule matches."""
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=utc_now, index=True, nullable=False)
    rule_id = Column(String(50), nullable=False, index=True)
    rule_name = Column(String(150), nullable=False)
    severity = Column(String(20), nullable=False)  # low, medium, high, critical
    mitre_technique_id = Column(String(50), nullable=False, index=True)
    mitre_technique_name = Column(String(150), nullable=False)
    mitre_tactic = Column(String(50), nullable=False)
    src_ip = Column(String(45), nullable=True, index=True)
    user = Column(String(100), nullable=True, index=True)
    description = Column(Text, nullable=False)
    log_event_ids = Column(JSON, nullable=False, default=list)
    incident_id = Column(Integer, ForeignKey("incidents.id", ondelete="SET NULL"), nullable=True, index=True)

    incident = relationship("Incident", back_populates="alerts")


class Incident(Base):
    """Correlated security incident aggregating alerts with LLM triage."""
    __tablename__ = "incidents"

    id = Column(Integer, primary_key=True, index=True)
    created_at = Column(DateTime, default=utc_now, index=True, nullable=False)
    updated_at = Column(DateTime, default=utc_now, onupdate=utc_now, nullable=False)
    title = Column(String(200), nullable=False)
    severity = Column(String(20), nullable=False)  # low, medium, high, critical
    status = Column(String(30), default="open", nullable=False)  # open, investigating, contained, closed
    src_ip = Column(String(45), nullable=True, index=True)
    affected_users = Column(JSON, nullable=False, default=list)
    mitre_techniques = Column(JSON, nullable=False, default=list)
    ai_summary = Column(Text, nullable=True)
    ai_recommendations = Column(JSON, nullable=True, default=list)
    ai_generated_at = Column(DateTime, nullable=True)

    alerts = relationship("Alert", back_populates="incident", lazy="selectin")
    response_actions = relationship("ResponseAction", back_populates="incident", cascade="all, delete-orphan", lazy="selectin")


class ResponseAction(Base):
    """Active response action executed or pending against an incident."""
    __tablename__ = "response_actions"

    id = Column(Integer, primary_key=True, index=True)
    incident_id = Column(Integer, ForeignKey("incidents.id", ondelete="CASCADE"), nullable=False, index=True)
    action_type = Column(String(50), nullable=False)  # block_ip, disable_user, create_ticket
    target = Column(String(150), nullable=False)
    status = Column(String(30), default="pending", nullable=False)  # pending, executed, failed
    performed_at = Column(DateTime, default=utc_now, nullable=False)
    details = Column(Text, nullable=True)

    incident = relationship("Incident", back_populates="response_actions")


class BlockedIP(Base):
    """Simulated firewall blocklist."""
    __tablename__ = "blocked_ips"

    id = Column(Integer, primary_key=True, index=True)
    ip_address = Column(String(45), unique=True, index=True, nullable=False)
    reason = Column(Text, nullable=True)
    blocked_at = Column(DateTime, default=utc_now, nullable=False)
    incident_id = Column(Integer, ForeignKey("incidents.id", ondelete="SET NULL"), nullable=True)
    status = Column(String(30), default="active", nullable=False)  # active, unblocked


class DisabledUser(Base):
    """Simulated identity provider disabled accounts."""
    __tablename__ = "disabled_users"

    id = Column(Integer, primary_key=True, index=True)
    username = Column(String(100), unique=True, index=True, nullable=False)
    reason = Column(Text, nullable=True)
    disabled_at = Column(DateTime, default=utc_now, nullable=False)
    incident_id = Column(Integer, ForeignKey("incidents.id", ondelete="SET NULL"), nullable=True)
    status = Column(String(30), default="disabled", nullable=False)  # disabled, enabled


class Ticket(Base):
    """Simulated ticketing system (e.g. Jira / ServiceNow)."""
    __tablename__ = "tickets"

    id = Column(Integer, primary_key=True, index=True)
    ticket_number = Column(String(50), unique=True, index=True, nullable=False)
    title = Column(String(200), nullable=False)
    description = Column(Text, nullable=False)
    severity = Column(String(20), default="medium", nullable=False)  # low, medium, high, critical
    status = Column(String(30), default="open", nullable=False)  # open, in_progress, resolved, closed
    incident_id = Column(Integer, ForeignKey("incidents.id", ondelete="SET NULL"), nullable=True)
    created_at = Column(DateTime, default=utc_now, nullable=False)
    updated_at = Column(DateTime, default=utc_now, onupdate=utc_now, nullable=False)
